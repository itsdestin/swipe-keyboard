"""Plasma 6.9 keyboard packages with Swipe Keyboard inside, generated from KDE's own packages at every launch.

KDE's rebuilt keyboard (plasma-keyboard 6.8.80+) finds keyboard packages under
`<data dir>/plasma/keyboard/keyboardpackages/<package>/metadata.json` and uses the FIRST package with a given id.
For each supported language we copy KDE's package into our private data folder, unchanged except for one thing:
the letter layout's file now points at a four-line wrapper that loads KDE's own file and then hands it to our
QML module (SwipeKeyboard69). The launcher puts our folder first in XDG_DATA_DIRS for the keyboard process only.

WHY a copy with the same id: the person's saved keyboard choices (org.kde.plasma.keyboard.en/mobile-qwerty) keep
working and pick up our copy; KDE's files are never modified; KDE's settings page (started without our variable)
still lists only KDE's packages. Rebuilt at every launch, so a KDE update can never leave a stale copy.
"""
import json
from pathlib import Path
import re
import shutil
import tempfile

# KDE package ids of the languages the engine supports (English, Spanish, French, German), in every region KDE ships.
SUPPORTED = (
    'org.kde.plasma.keyboard.en',
    'org.kde.plasma.keyboard.es_ES',
    'org.kde.plasma.keyboard.es_MX',
    'org.kde.plasma.keyboard.fr_FR',
    'org.kde.plasma.keyboard.fr_CA',
    'org.kde.plasma.keyboard.de_DE',
)
PACKAGE_DIR = Path('plasma/keyboard/keyboardpackages')
MARKER = 'X-SwipeKeyboard'
TYPE_NAME = re.compile(r'[A-Z][A-Za-z0-9_]*')

WRAPPER = '''// Generated by Swipe Keyboard (integration/plasma69.py) at every keyboard start. Do not edit.
// Loads KDE's {source} unchanged, then lets Swipe Keyboard add swiping and its suggestion row.
import QtQuick

{type_name} {{
    id: swipeKeyboardRoot
    // WHY created at run time instead of imported: if Swipe Keyboard's module cannot load, this layout is still
    // exactly KDE's and the keyboard keeps working; only the warning below tells that swiping is off.
    Component.onCompleted: {{
        const attach = Qt.createComponent("SwipeKeyboard69", "SwipeAttach");
        if (attach.status === Component.Ready) {{
            attach.createObject(swipeKeyboardRoot, {{ target: swipeKeyboardRoot }});
        }} else {{
            console.warn("Swipe Keyboard is unavailable; the plain KDE keyboard is used:", attach.errorString());
        }}
    }}
}}
'''


def is_new_core(data_dirs):
    """True when KDE's rebuilt keyboard core is installed: its packages exist in a system data folder."""
    return any((Path(d) / PACKAGE_DIR / 'org.kde.plasma.keyboard.en' / 'metadata.json').is_file() for d in data_dirs)


def find_stock(data_dirs, package_id, exclude=None):
    """KDE's package folder for `package_id`: the first data folder that has one, as KDE's own lookup does."""
    for d in data_dirs:
        root = Path(d) / PACKAGE_DIR
        if exclude is not None and root.resolve() == Path(exclude).resolve():
            continue
        if not root.is_dir():
            continue
        # WHY scan, not join: KDE takes the id from metadata.json, the folder name is only a fallback.
        for folder in sorted(root.iterdir()):
            metadata = folder / 'metadata.json'
            if not metadata.is_file():
                continue
            try:
                plugin_id = json.loads(metadata.read_text())['KPlugin']['Id']
            except (OSError, ValueError, KeyError, TypeError):
                plugin_id = folder.name
            if plugin_id == package_id:
                return folder
    return None


def wrap_layout(package, layout):
    """Points one layout definition at a wrapper. Returns False when its format is unknown (left stock)."""
    files = layout.get('Files')
    if isinstance(files, dict) and isinstance(files.get('main'), str):
        # plasma-keyboard master (2026-10): "Files": {"main": ..., "symbols": ...}
        target, setter = files['main'], lambda value: files.__setitem__('main', value)
    elif isinstance(layout.get('File'), str):
        # MR !179 (KeyboardLayoutDefinition): "File": one file that also names the symbol pages.
        target, setter = layout['File'], lambda value: layout.__setitem__('File', value)
    else:
        return False
    relative = Path(target)
    if relative.is_absolute() or '..' in relative.parts or relative.suffix != '.qml':
        return False
    source = package / 'contents/layouts' / relative
    if not source.is_file() or not TYPE_NAME.fullmatch(relative.stem):
        return False
    wrapper = relative.with_name('SwipeKeyboard' + relative.stem + '.qml')
    # WHY same folder: the wrapper refers to KDE's file by its type name, which QML resolves in its own folder,
    # and KDE's file keeps its relative imports ("shared" as Shared) exactly as before.
    (package / 'contents/layouts' / wrapper).write_text(WRAPPER.format(source=relative.as_posix(), type_name=relative.stem))
    setter(wrapper.as_posix())
    return True


def generate_package(stock, destination):
    """Copies one KDE package to `destination` and wraps its letter layouts. Returns the number wrapped."""
    shutil.copytree(stock, destination, symlinks=False)
    metadata_path = destination / 'metadata.json'
    metadata = json.loads(metadata_path.read_text())
    layouts = metadata.get('X-Plasma-Keyboard', {}).get('KeyboardLayouts', [])
    if not isinstance(layouts, list):
        raise ValueError(f'{stock.name}: unexpected keyboard package format')
    wrapped = sum(1 for layout in layouts if isinstance(layout, dict) and wrap_layout(destination, layout))
    metadata[MARKER] = {'GeneratedFrom': str(stock), 'Version': 1}
    metadata_path.write_text(json.dumps(metadata, indent=4, ensure_ascii=False) + '\n')
    return wrapped


def build_packages(data_dirs, overlay):
    """Builds `overlay`/plasma/keyboard/keyboardpackages from KDE's packages; returns the generated package ids.

    Staged completely, then swapped in with a rename, so a failure keeps the last working copy (or none).
    Raises ValueError when no supported language could be wrapped: the launcher then starts KDE's plain keyboard.
    """
    overlay = Path(overlay)
    destination = overlay / PACKAGE_DIR
    destination.parent.mkdir(parents=True, exist_ok=True)
    generated = []
    with tempfile.TemporaryDirectory(prefix='.keyboardpackages-', dir=destination.parent) as temp:
        staged = Path(temp) / 'keyboardpackages'
        staged.mkdir()
        for package_id in SUPPORTED:
            stock = find_stock(data_dirs, package_id, exclude=destination)
            if stock is None:
                continue
            if generate_package(stock, staged / stock.name):
                generated.append(package_id)
            else:
                shutil.rmtree(staged / stock.name)  # nothing we understand: leave this language to KDE
        if not generated:
            raise ValueError('No Plasma Keyboard package could take Swipe Keyboard (unknown package format).')
        previous = destination.with_name(destination.name + '.previous')
        if previous.exists():
            shutil.rmtree(previous)
        if destination.exists():
            destination.rename(previous)
        try:
            staged.rename(destination)
        except OSError:
            if previous.exists():
                previous.rename(destination)
            raise
        if previous.exists():
            shutil.rmtree(previous)
    return generated


def main():
    """`plasma69.py DATA_DIRS OVERLAY` (used by the tests): prints the generated ids."""
    import sys
    data_dirs = sys.argv[1].split(':')
    print(','.join(build_packages(data_dirs, sys.argv[2])))


if __name__ == '__main__':
    main()
